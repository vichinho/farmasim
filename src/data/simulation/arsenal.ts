const trailingFormTokens = new Set([
  "CM", "CP", "FA", "FC", "AM", "TU", "MT", "SP", "SA", "CA", "UN", "FR", "JR", "SO",
  "GOT", "INH", "OV", "SUP", "AMP", "FCO", "JBE", "SOL", "UNG", "POLVO", "SUSP", "SUSPENSION",
  "GEL", "CREMA", "PARCHE", "JERINGA", "COMP", "COM", "CAP",
]);

function slugify(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function titleCase(value: string) {
  return value.toLowerCase().replace(/(^|[\s/+()-])([a-záéíóúñ])/g, (_, prefix, char) => `${prefix}${char.toUpperCase()}`);
}

function normalizeMedicationName(description: string) {
  const upper = description.toUpperCase().replace(/\s+/g, " ").trim();
  const digitIndex = upper.search(/\d/);
  const prefix = (digitIndex >= 0 ? upper.slice(0, digitIndex) : upper).trim();
  const tokens = prefix.split(" ");
  while (tokens.length && trailingFormTokens.has(tokens.at(-1)?.replace(/[().,]/g, "") ?? "")) tokens.pop();
  const normalized = tokens.join(" ").replace(/[\s/+.-]+$/g, "").trim() || upper;
  if (normalized === "LEVOTIROXINA SODICA") return "LEVOTIROXINA";
  return normalized;
}

function extractStrength(description: string) {
  const match = description.match(/\d+(?:[.,]\d+)?\s*(?:MCG|MG|G|UI|U|MEQ|MMOL|%)(?:\s*\/\s*\d+(?:[.,]\d+)?\s*(?:ML|G|DOSIS|GOTA))?/i);
  return match ? match[0].toUpperCase().replace(",", ".") : "NO ESPECIFICADA EN DESCRIPCIÓN TRAKCARE";
}

export const medicationPresentations: MedicationPresentation[] = rawAtencionAbierta
  .split("\n")
  .filter(Boolean)
  .map((row) => {
    const [sourceCode, sourceDescription, pharmaceuticalForm, dispensingUnit] = row.split("|");
    const normalizedName = normalizeMedicationName(sourceDescription);
    return {
      id: `trakcare-${sourceCode.toLowerCase()}`,
      medicationId: slugify(normalizedName),
      medicationName: titleCase(normalizedName),
      strength: extractStrength(sourceDescription),
      pharmaceuticalForm,
      careSetting: "atencion-abierta" as const,
      sourceCode,
      sourceDescription,
      dispensingUnit: dispensingUnit || undefined,
    };
  });

const presentationsByMedication = new Map<string, MedicationPresentation[]>();
for (const presentation of medicationPresentations) {
  presentationsByMedication.set(
    presentation.medicationId,
    [...(presentationsByMedication.get(presentation.medicationId) ?? []), presentation],
  );
}

export const medications: Medication[] = [...presentationsByMedication.entries()]
  .map(([id, presentations]) => ({ id, name: presentations[0].medicationName }))
  .sort((left, right) => left.name.localeCompare(right.name, "es"));

export const atencionAbierta: AtencionAbiertaEntry[] = [...presentationsByMedication.entries()]
  .map(([medicationId, presentations]) => ({
    medicationId,
    presentationIds: presentations.map((presentation) => presentation.id),
  }))
  .sort((left, right) => left.medicationId.localeCompare(right.medicationId));

export const ambulatoryArsenal = medicationPresentations;

export function alternativeStrengthPresentations(presentationId: string) {
  const source = medicationPresentations.find((presentation) => presentation.id === presentationId);
  if (!source) return [];
  return (presentationsByMedication.get(source.medicationId) ?? []).filter(
    (candidate) => candidate.id !== source.id && candidate.strength !== source.strength,
  );
}
